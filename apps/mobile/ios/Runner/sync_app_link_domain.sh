#!/bin/sh
# Writes ios/Flutter/AppLink.xcconfig from Flutter DART_DEFINES (APP_LINK_HOST).
set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
FLUTTER_DIR="${SCRIPT_DIR}/../Flutter"
GENERATED="${FLUTTER_DIR}/Generated.xcconfig"
OUTPUT="${FLUTTER_DIR}/AppLink.xcconfig"
DEFAULT_HOST="lanonna-dev.firebaseapp.com"

host=""
if [ -f "${GENERATED}" ]; then
  dart_defines=$(grep -E '^DART_DEFINES=' "${GENERATED}" | tail -1 | cut -d= -f2- | tr -d '\r')
  if [ -n "${dart_defines}" ]; then
    IFS=',' read -ra ENTRIES <<EOF
${dart_defines}
EOF
    for entry in "${ENTRIES[@]}"; do
      decoded=$(printf '%s' "${entry}" | base64 --decode 2>/dev/null || true)
      case "${decoded}" in
        APP_LINK_HOST=*)
          host="${decoded#APP_LINK_HOST=}"
          ;;
      esac
    done
  fi
fi

if [ -z "${host}" ]; then
  host="${DEFAULT_HOST}"
fi

printf '// Generated by sync_app_link_domain.sh — do not edit by hand.\nAPP_LINK_DOMAIN=%s\n' "${host}" > "${OUTPUT}"
