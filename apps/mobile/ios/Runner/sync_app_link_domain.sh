#!/bin/bash
# Xcode build phase: keeps APP_LINK_DOMAIN (Associated Domains entitlement) in
# sync with APP_LINK_HOST from Flutter DART_DEFINES.
#
# Xcode resolves build settings before any build phase runs, so a value written
# here only applies to the next build. When the decoded host differs from the
# APP_LINK_DOMAIN this build is using, the script writes the override file and
# FAILS so a mismatched entitlement is never signed; re-run the build.
# Output: ios/Flutter/AppLink.generated.xcconfig (gitignored, never committed).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
FLUTTER_DIR="${SCRIPT_DIR}/../Flutter"
GENERATED="${FLUTTER_DIR}/Generated.xcconfig"
OUTPUT="${FLUTTER_DIR}/AppLink.generated.xcconfig"
DEFAULT_HOST="lanonna-dev.firebaseapp.com"

host=""
if [[ -f "${GENERATED}" ]]; then
  dart_defines="$(grep -E '^DART_DEFINES=' "${GENERATED}" | tail -1 | cut -d= -f2- | tr -d '\r' || true)"
  if [[ -n "${dart_defines}" ]]; then
    IFS=',' read -r -a entries <<< "${dart_defines}"
    for entry in "${entries[@]}"; do
      decoded="$(printf '%s' "${entry}" | base64 --decode 2>/dev/null || true)"
      case "${decoded}" in
        APP_LINK_HOST=*) host="${decoded#APP_LINK_HOST=}" ;;
      esac
    done
  fi
fi
host="${host:-${DEFAULT_HOST}}"

# Only a plain lowercase hostname may reach the xcconfig and the entitlement.
if [[ ! "${host}" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]]; then
  echo "error: APP_LINK_HOST '${host}' is not a valid hostname (placeholder not replaced?)." >&2
  exit 1
fi

printf '// Generated by sync_app_link_domain.sh - do not edit or commit.\nAPP_LINK_DOMAIN=%s\n' "${host}" > "${OUTPUT}"

current="${APP_LINK_DOMAIN:-}"
if [[ -n "${current}" && "${current}" != "${host}" ]]; then
  echo "error: App Link domain changed from ${current} to ${host}. Updated AppLink.generated.xcconfig; run the build again so the entitlement uses it." >&2
  exit 1
fi
